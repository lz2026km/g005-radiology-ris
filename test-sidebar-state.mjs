import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext();
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:5199/g005-radiology-ris/');
await p.evaluate(() => localStorage.setItem('ris_current_user', JSON.stringify({id:'A001',name:'系统管理员',role:'管理员',department:'信息科'})));
await p.goto('http://127.0.0.1:5199/g005-radiology-ris/worklist');
await p.waitForTimeout(2000);
const before = await p.evaluate(() => Array.from(document.querySelectorAll('aside a')).slice(0, 8).map(a => ({ href: a.getAttribute('href'), text: a.textContent?.slice(0, 20) })));
console.log('BEFORE click:', JSON.stringify(before, null, 2));
const link17 = await p.$('aside a[href="/report-review"]');
console.log('Found /report-review:', !!link17);
await p.click('aside a[href="/report-review"]');
await p.waitForTimeout(2500);
const after = await p.evaluate(() => Array.from(document.querySelectorAll('aside a')).slice(0, 8).map(a => ({ href: a.getAttribute('href'), text: a.textContent?.slice(0, 20) })));
console.log('AFTER click report-review:', JSON.stringify(after, null, 2));
const link17b = await p.$('aside a[href="/report-review"]');
console.log('Still found /report-review:', !!link17b);
await b.close();
