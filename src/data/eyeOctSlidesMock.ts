import type { OctBscanSeries, OctBscanSlice } from "../types/eye";

const NOW = Date.now();

function makeSlices(
  seriesId: string,
  studyId: string,
  count: number,
  eyeSide: "OD" | "OS" | "OU",
  scanPattern: string,
  startIdx: number,
): OctBscanSlice[] {
  const slices: OctBscanSlice[] = [];
  for (let i = 1; i <= count; i++) {
    const sliceNum = i + startIdx;
    slices.push({
      id: `obs-${seriesId}-${String(i).padStart(3, "0")}`,
      seriesId,
      studyId,
      sliceNumber: i,
      bscanIndex: i,
      url: `/mock/eye/oct-bscan-${seriesId}-${String(i).padStart(3, "0")}.jpg`,
      thumbnail: `/mock/eye/oct-bscan-${seriesId}-${String(i).padStart(3, "0")}-thumb.jpg`,
      description: `B-scan #${i} (${scanPattern})`,
      eyeSide,
      rows: 512,
      columns: 1024,
      pixelSpacing: [0.012, 0.004],
      sliceLocation: i * 0.25,
      scanPosition: i <= count / 2 ? "horizontal" : "vertical",
      bscanType: scanPattern,
      qualityScore: Math.round(60 + Math.random() * 35),
      segmentationValid: Math.random() > 0.1,
    });
  }
  return slices;
}

