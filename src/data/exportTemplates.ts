export function findExportTemplate(id: string): ExportTemplateDefinition | undefined {
  return EXPORT_TEMPLATES.find(t => t.id === id);
}

export function filterExportTemplates(category?: string, format?: string): ExportTemplateDefinition[] {
  return EXPORT_TEMPLATES.filter(t =>
    (!category || t.category === category) &&
    (!format || t.format === format)
  );
}